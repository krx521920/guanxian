import { test, expect, type Page } from '@playwright/test'

async function query(page: Page, text = '查询监测企业') {
  await page.goto('/tests/ui/assistant-preview.html')
  await page.getByRole('button', { name: '打开管线智能助手' }).click()
  await page.getByLabel('向管线智能助手提问').fill(text)
  await page.getByRole('button', { name: '发送问题' }).click()
}
test('unselected association NON_NULL receipts render cards and a completed answer', async ({ page }) => {
  await query(page, '未选择协会，查询会员企业')
  await expect(page.locator('.business-card')).toHaveCount(3)
  await expect(page.locator('.query-receipt')).toContainText('全部协会（仅限当前账号有权查看的资料）')
  await expect(page.locator('.query-receipt summary')).toContainText('共 12 条 · 展示 3 条')
  await expect(page.locator('.assistant-trace')).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
test('a missing source link does not interrupt an unselected association answer', async ({ page }) => {
  await query(page, '未选择协会，查询招标，无原文链接')
  await expect(page.locator('.query-receipt')).toContainText('全部协会（仅限当前账号有权查看的资料）')
  await expect(page.locator('.assistant-trace')).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.getByRole('link', { name: '来源原文 ↗', exact: true })).toHaveCount(0)
})
test('cards expose actual scope/counts, fresh authorized details and keyboard return', async ({ page }) => {
  await query(page)
  await expect(page.locator('.business-card')).toHaveCount(3)
  await expect(page.locator('.query-receipt summary')).toContainText('共 12 条 · 展示 3 条')
  await expect(page.locator('.receipt-meta')).toContainText('监测')
  await expect(page.locator('.business-results')).not.toContainText('测试联系人')
  await expect(page.locator('.assistant-trace')).toBeVisible()
  await page.getByRole('button', { name: '查看详情', exact: true }).first().click()
  const detail = page.getByRole('dialog', { name: '虚构·京华监测科技 企业详情' })
  await expect(detail).toContainText('测试联系人')
  const reads = await page.evaluate(() => window.__guanxianPreview.memberReads)
  expect(reads).toHaveLength(1)
  await page.screenshot({ path: '../../test-results/assistant-business/detail.png', fullPage: true })
  await page.keyboard.press('Escape')
  await expect(detail).toHaveCount(0)
  await expect(page.getByRole('dialog', { name: '管线智能助手', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '查看详情', exact: true }).first()).toBeFocused()
  await page.screenshot({ path: '../../test-results/assistant-business/cards.png', fullPage: true })
})
test('selected comparison reads both profiles again, renders missing values and returns', async ({ page }) => {
  await query(page)
  await expect(page.locator('.assistant-trace')).toBeVisible()
  await page.getByRole('button', { name: '加入对比', exact: true }).first().click()
  await page.getByRole('button', { name: '加入对比', exact: true }).first().click()
  await page.getByRole('button', { name: '对比所选企业', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '会员企业对比', exact: true })
  await expect(dialog.getByRole('columnheader')).toHaveCount(3)
  await expect(dialog).toContainText('未提供')
  const reads = await page.evaluate(() => window.__guanxianPreview.memberReads)
  expect(new Set(reads).size).toBe(2)
  await page.screenshot({ path: '../../test-results/assistant-business/comparison.png', fullPage: true })
  await dialog.getByRole('button', { name: '关闭业务结果' }).click()
  await expect(dialog).toHaveCount(0)
})
test('permission change blocks old details and comparison without partial fallback', async ({ page }) => {
  await query(page)
  await expect(page.locator('.assistant-trace')).toBeVisible()
  await page.evaluate(() => window.__guanxianPreview.unavailableMembers.add('20000000-0000-4000-8000-000000000002'))
  await page.getByRole('button', { name: '查看详情', exact: true }).nth(1).click()
  await expect(page.locator('.business-results [role=alert]')).toContainText('权限发生变化')
  await expect(page.locator('.business-dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '加入对比', exact: true }).first().click()
  await page.getByRole('button', { name: '加入对比', exact: true }).first().click()
  await page.getByRole('button', { name: '对比所选企业', exact: true }).click()
  await expect(page.locator('.business-results [role=alert]')).toContainText('权限发生变化')
  await expect(page.locator('.business-dialog')).toHaveCount(0)
})
